const ALL_LOCALES = [
  'en', 'hi', 'bn', 'te', 'mr', 'ta', 'gu', 'kn', 'ml', 'pa', 'or', 'as', 'ur', 'mai', 'ne', 'kok', 'sd', 'dog'
];

// Read existing content
const currentFileContent = fs.readFileSync(filePath, 'utf8');

// Build replacement object
let updatedContent = currentFileContent;

ALL_LOCALES.forEach(loc => {
  if (loc === 'en') return;
  // Regex to find: loc: {\n...}
  const locRegex = new RegExp(`(\\s+${loc}:\\s*\\{[\\s\\S]*?\\n\\s*\\},)`, 'm');
  const match = updatedContent.match(locRegex);
  if (match) {
    let block = match[1];
    // Append keys that do not exist yet in this block
    let additions = '';
    for (const [key, transMap] of Object.entries(LANDING_TRANSLATIONS)) {
      const translatedVal = transMap[loc] || transMap.hi || key;
      const escapedKey = key.replace(/'/g, "\\'");
      const escapedVal = translatedVal.replace(/'/g, "\\'");
      if (!block.includes(`'${escapedKey}':`)) {
        additions += `    '${escapedKey}': '${escapedVal}',\n`;
      }
    }
    if (additions) {
      // insert before closing \n  },
      const lastBraceIndex = block.lastIndexOf('},');
      const newBlock = block.slice(0, lastBraceIndex) + additions + block.slice(lastBraceIndex);
      updatedContent = updatedContent.replace(block, newBlock);
    }
  }
});

fs.writeFileSync(filePath, updatedContent, 'utf8');
if (fs.existsSync(mainWebFilePath)) {
  fs.writeFileSync(mainWebFilePath, updatedContent, 'utf8');
}
